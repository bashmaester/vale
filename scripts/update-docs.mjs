// Regenerates the deploy-only docs that need fresh CI metadata.
// Human-written docs (HANDOFF.md, ARCHITECTURE.md, CHANGELOG.md, CI.md) stay
// untouched; this script adds BUILD.md, DEPLOY_STATUS.md, manifest.json and
// a small docs/index.html that links everything together.
import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const p = (x) => resolve(root, x);

function git(cmd, fallback = 'unknown') {
  try { return execSync(cmd, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim() || fallback; }
  catch { return fallback; }
}
const sha = process.env.GITHUB_SHA || git('git rev-parse HEAD');
const shortSha = sha.slice(0, 8);
const branch = process.env.GITHUB_REF_NAME || git('git branch --show-current', 'detached');
const runId = process.env.GITHUB_RUN_ID || 'local';
const runUrl = process.env.GITHUB_SERVER_URL && process.env.GITHUB_REPOSITORY && runId !== 'local'
  ? `${process.env.GITHUB_SERVER_URL}/${process.env.GITHUB_REPOSITORY}/actions/runs/${runId}`
  : '';
const builtAt = new Date().toISOString();
const pkg = JSON.parse(await readFile(p('package.json'), 'utf8'));

async function sizeOf(file) {
  try { return (await stat(p(file))).size; } catch { return 0; }
}
const indexBytes = await sizeOf('index.html');
const readme = await readFile(p('README.md'), 'utf8');
const handoff = await readFile(p('docs/HANDOFF.md'), 'utf8').catch(() => '# Handoff\n\nNot written yet.\n');
const architecture = await readFile(p('docs/ARCHITECTURE.md'), 'utf8').catch(() => '');
const changelog = await readFile(p('docs/CHANGELOG.md'), 'utf8').catch(() => '');
const ci = await readFile(p('docs/CI.md'), 'utf8').catch(() => '');

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const firstPara = (s, n = 420) => s.replace(/\r/g, '').split(/\n\s*\n/).find((x) => x.trim() && !x.trim().startsWith('#')) || s.slice(0, n);

const buildMd = `# Build metadata

- **Commit:** \`${sha}\` (\`${shortSha}\`)
- **Branch:** \`${branch}\`
- **Built:** ${builtAt}
- **Package version:** ${pkg.version}
- **Self-contained film:** \`index.html\` — ${indexBytes.toLocaleString('en-US')} bytes
- **CI run:** ${runUrl ? `[${runId}](${runUrl})` : runId}

This file is generated by \`npm run docs\` / \`.github/workflows/deploy-pages.yml\`.
`;

const deployMd = `# Deploy status

| Field | Value |
| --- | --- |
| Status | deployed by GitHub Actions |
| Branch | \`${branch}\` |
| Commit | \`${shortSha}\` |
| Built | ${builtAt} |
| Film | [../index.html](../index.html) |
| Docs index | [index.html](index.html) |
| Handoff | [HANDOFF.md](HANDOFF.md) |
| Architecture | [ARCHITECTURE.md](ARCHITECTURE.md) |
| Changelog | [CHANGELOG.md](CHANGELOG.md) |
| CI notes | [CI.md](CI.md) |

If a session is interrupted, start from **HANDOFF.md** — it records the current
objective, what works, what is unfinished, and the next concrete steps.
`;

const manifest = {
  generatedAt: builtAt,
  branch,
  commit: sha,
  shortCommit: shortSha,
  runId,
  runUrl: runUrl || null,
  version: pkg.version,
  indexBytes,
  docs: ['HANDOFF.md', 'ARCHITECTURE.md', 'CHANGELOG.md', 'CI.md', 'BUILD.md', 'DEPLOY_STATUS.md', 'index.html'],
};

const cards = [
  { href: 'HANDOFF.md', title: 'HANDOFF', text: firstPara(handoff) },
  { href: 'ARCHITECTURE.md', title: 'ARCHITECTURE', text: firstPara(architecture) },
  { href: 'CHANGELOG.md', title: 'CHANGELOG', text: firstPara(changelog) },
  { href: 'CI.md', title: 'CI / PAGES', text: firstPara(ci) },
  { href: 'BUILD.md', title: 'BUILD', text: `Commit ${shortSha} on ${branch}, built ${builtAt}.` },
  { href: 'DEPLOY_STATUS.md', title: 'DEPLOY STATUS', text: 'Fresh deployment metadata for this Pages build.' },
];

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>VALE — docs &amp; handoff</title>
<style>
:root{color-scheme:dark}*{box-sizing:border-box}
body{margin:0;background:#070908;color:#d7ded4;font:14px/1.6 ui-monospace,SFMono-Regular,Menlo,monospace}
header{padding:28px clamp(18px,5vw,64px);border-bottom:1px solid #26332c}
h1{margin:0 0 6px;font-size:22px;letter-spacing:.16em;color:#eef3e8}
.meta{color:#7d9688;font-size:12px}
main{max-width:1040px;margin:0 auto;padding:28px clamp(18px,5vw,64px) 64px}
a{color:#56c7b7;text-decoration:none}a:hover{text-decoration:underline}
.film{display:inline-block;margin:0 0 26px;padding:10px 16px;border:1px solid #56c7b7;border-radius:6px;background:#101713;font-weight:700}
.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(280px,1fr));gap:14px}
.card{display:block;padding:16px;border:1px solid #31413a;border-radius:8px;background:#0c110e;color:inherit;text-decoration:none}
.card:hover{border-color:#56c7b7;text-decoration:none;background:#101a15}
.card h2{margin:0 0 8px;font-size:12px;letter-spacing:.14em;color:#eef3e8}
.card p{margin:0;color:#8fa397;font-size:12px}
pre{white-space:pre-wrap;word-break:break-word;background:#0a0e0b;border:1px solid #26332c;border-radius:8px;padding:16px;color:#9fb2a5;font-size:12px;max-height:420px;overflow:auto}
h2.sec{font-size:12px;letter-spacing:.14em;color:#7d9688;margin:34px 0 10px}
footer{padding:20px clamp(18px,5vw,64px);border-top:1px solid #26332c;color:#617569;font-size:11px}
</style>
</head>
<body>
<header>
  <h1>VALE / DOCS &amp; HANDOFF</h1>
  <div class="meta">branch ${esc(branch)} · commit ${esc(shortSha)} · built ${esc(builtAt)} · index.html ${indexBytes.toLocaleString('en-US')} bytes</div>
</header>
<main>
  <a class="film" href="../index.html">▶ open the self-contained film</a>
  <div class="grid">
    ${cards.map((c) => `<a class="card" href="${c.href}"><h2>${esc(c.title)}</h2><p>${esc(c.text.slice(0, 360))}</p></a>`).join('\n    ')}
  </div>
  <h2 class="sec">README (live copy)</h2>
  <pre>${esc(readme)}</pre>
  <h2 class="sec">QUICK LINKS</h2>
  <p><a href="HANDOFF.md">HANDOFF.md</a> · <a href="ARCHITECTURE.md">ARCHITECTURE.md</a> · <a href="CHANGELOG.md">CHANGELOG.md</a> · <a href="CI.md">CI.md</a> · <a href="BUILD.md">BUILD.md</a> · <a href="DEPLOY_STATUS.md">DEPLOY_STATUS.md</a> · <a href="manifest.json">manifest.json</a></p>
</main>
<footer>Generated by scripts/update-docs.mjs. Human-authored docs are committed in <code>docs/</code>; BUILD/DEPLOY/manifest/index are regenerated on every deploy.</footer>
</body>
</html>
`;

await mkdir(p('docs'), { recursive: true });
await writeFile(p('docs/BUILD.md'), buildMd, 'utf8');
await writeFile(p('docs/DEPLOY_STATUS.md'), deployMd, 'utf8');
await writeFile(p('docs/manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
await writeFile(p('docs/index.html'), html, 'utf8');
console.log(`Docs updated for ${branch}@${shortSha} (${builtAt})`);
